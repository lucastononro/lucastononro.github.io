// The comment box, dressed as part of the site.
//
// giscus renders inside an iframe, so styles.css cannot reach it. What it does
// accept is a URL to a stylesheet, which it loads in there — that is what this
// file builds. Inside the frame the markup is GitHub Primer, so the work is
// mostly rebinding Primer's variables to the paper-and-terracotta palette.
//
// Two stylesheets come out of one template, one per theme, because the frame
// has no idea which way the Tonon switch is pointing; theme.js tells it by
// swapping the URL. Keep the palettes below in step with the ones at the top
// of static/styles.css — same values, second home.

