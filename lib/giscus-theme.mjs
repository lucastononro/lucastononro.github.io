  'https://fonts.googleapis.com/css2' +
  '?family=Alegreya:ital,wght@0,400..800;1,400..700' +
  '&family=Alegreya+Sans:ital,wght@0,400;0,500;0,700;1,400' +
  '&family=IBM+Plex+Mono:wght@400;500' +
  '&display=swap'

